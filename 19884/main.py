    v = int(input('Ширина ветки: '))
  
    # Запрашиваем количество веток и преобразуем ввод в целое число
    n = int(input('Кол-во: '))
  
    # Инициализируем пустую строку для накопленного результата
    res = ''
  
    # Цикл для каждой ветки
    for j in range(0, n):
        # Инициализируем пустую строку для текущей ветки
        s = '' 
        
        # Цикл для построения ширины текущей ветки
        for i in range(0, v):
            # Добавляем звездочку к строке текущей ветки
            s += '*'
            # Вместо этого было 'res += 's\n'', которое добавляло строку 's' как текст 's', а не значение строки s
